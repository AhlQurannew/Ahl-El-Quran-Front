export function thumnRange(hizb: number, thumn: number): ThumnRange {
  const [fromSurah, fromVerse, toSurah, toVerse] = THUMN_RANGES[(hizb - 1) * THUMN_PER_HIZB + thumn - 1];
  return { fromSurah, fromVerse, toSurah, toVerse };
}

/** The Hizb and Thumn containing this verse. */
export function locateThumn(surah: number, verse: number): { hizb: number; thumn: number } {
  let index = 0;
  for (let i = 1; i < THUMN_RANGES.length; i += 1) {
    const [s, v] = THUMN_RANGES[i];
    if (s > surah || (s === surah && v > verse)) break;
    index = i;
  }
  return { hizb: Math.floor(index / THUMN_PER_HIZB) + 1, thumn: (index % THUMN_PER_HIZB) + 1 };
}
